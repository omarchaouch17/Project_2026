def to_canonical_diagnosis(text):
    """English name of a stored diagnosis (old German rows are converted; free text stays as typed)."""
    if text is None:
        return None
    return LEGACY_DIAGNOSES.get(text.strip().lower(), text)


def to_canonical_category(text):
    """English name of a stored category (old German rows are converted)."""
    return LEGACY_CATEGORIES.get(text, text)


def translate_diagnosis(text, language):
    """Return the diagnosis in the target language (unknown free text stays unchanged)."""
    if text is None:
        return None
    entry = _diagnosis_lookup.get(text.strip().lower())
    return entry[language] if entry else text


def category_name(key, language):
    """Display name of a category in the target language (unknown values stay unchanged)."""
    entry = CATEGORY_TRANSLATIONS.get(to_canonical_category(key))
    return entry[language] if entry else key


